import { Router } from "express";
import * as controller from "../controllers/book.controller.js";
import * as categories from "../controllers/category.controller.js";
import * as publishers from "../controllers/publisher.controller.js";
import * as bookPublishers from "../controllers/book-publisher.controller.js";
import * as authors from "../controllers/author.controller.js";
const router = Router();
router.get("/authors", authors.list);
router.get("/authors/:id", authors.detail);
router.post("/authors", authors.create);
router.get("/books", controller.list);
router.get("/books/:id", controller.detail);
router.post("/books", controller.create);
router.post("/books/match", controller.match);
router.put("/books/:id", controller.update); // PUT/PATCH both update supplied fields, documented for simple Postman use.
router.patch("/books/:id", controller.update);
router.patch("/books/:id/stock", controller.addStock);
router.delete("/books/:id", controller.remove);
router.get("/books/:id/publishers", bookPublishers.list);
router.put("/books/:id/publishers", bookPublishers.replace);
router.post("/books/:id/publishers", bookPublishers.add);
router.delete("/books/:id/publishers/:publisherId", bookPublishers.remove);
router.get("/publishers", publishers.list);
router.get("/publishers/:id", publishers.detail);
router.get("/publishers/:id/books", publishers.listBooks);
router.post("/publishers", publishers.create);
router.patch("/publishers/:id", publishers.update);
router.put("/publishers/:id", publishers.update);
router.delete("/publishers/:id", publishers.remove);
router.get("/categories", categories.list);
router.get("/categories/:id", categories.detail);
router.post("/categories", categories.create);
router.put("/categories/:id", categories.update);
router.patch("/categories/:id", categories.update);
router.delete("/categories/:id", categories.remove);
export default router;
