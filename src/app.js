import express from 'express';
import cors from 'cors';
import router from './routes/book.routes.js';
import authRouter from './routes/auth.routes.js';
import userRouter from './routes/user.routes.js';
import publicRouter from './routes/public.routes.js';
import orderRouter from './routes/order.routes.js';
import adminOrderRouter from './routes/admin-order.routes.js';
import shippingRouter from './routes/shipping.routes.js';
import webhookRouter from './routes/webhook.routes.js';
import { authenticate, requireAdmin, requireCustomer } from './middleware/auth.js';
import {pool} from './config/db.js';
export const app = express();

app.disable('x-powered-by');
app.use(cors({ origin: process.env.CORS_ORIGIN || 'http://localhost:5173' }));
app.use(express.json({ limit: '1mb' }));
app.get('/api/health', async (req, res) => {
  await pool.execute('SELECT 1');
  res.json({ status: 'ok' });
});
app.use('/api',publicRouter);
app.use('/api/auth',authRouter);
app.use('/api/shipping', shippingRouter);
app.use('/api/webhooks', webhookRouter);
app.use('/api/orders', authenticate, requireCustomer, orderRouter);
app.use('/api/admin/orders', authenticate, requireAdmin, adminOrderRouter);
app.use('/api/admin', authenticate, requireAdmin, router);
app.use('/api/admin/users', authenticate, requireAdmin, userRouter);
app.use((req,res)=>res.status(404).json({message:'API không tồn tại'}));
app.use((e,req,res,next)=>{let status=e.status||500,message=e.message;if(e.code==='ER_ROW_IS_REFERENCED_2'){status=409;message='Sách đang liên kết với tác giả/đơn hàng/đánh giá. Có thể dùng is_active=false để ngừng bán.';}else if(e.code==='ER_NO_REFERENCED_ROW_2'){status=400;message='Thể loại không tồn tại';}else if(e.code==='ER_DUP_ENTRY'){status=409;message='Dữ liệu bị trùng';}else if(['ER_CHECK_CONSTRAINT_VIOLATED','ER_BAD_NULL_ERROR','ER_DATA_TOO_LONG','ER_TRUNCATED_WRONG_VALUE'].includes(e.code)){status=400;message='Dữ liệu không hợp lệ';}if(status>=500){console.error(e.message);message=e.expose||status===502||status===503?e.message:'Không xử lý được yêu cầu. Kiểm tra MySQL và terminal backend.';}res.status(status).json({message});});
